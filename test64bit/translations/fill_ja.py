def polish_ja_in_table(table: dict[str, dict[str, str]]) -> int:
    """Replace Chinese loanwords and patch EN fields that were left in Chinese."""
    updated = 0
    for row in table.values():
        ja = row.get("ja", "")
        new_ja = ja.replace("定位", "マーキング")
        if new_ja != ja:
            row["ja"] = new_ja
            updated += 1
    en_patches = {
        "皮肤分析失败。\\n": "Skin analysis failed.\\n",
        "皮肤分析部分完成：成功 %1 项，失败 %2 项。\\n%3": (
            "Skin analysis partially complete: %1 succeeded, %2 failed.\\n%3"
        ),
        "请使用右侧「取消」或「保存」\\n退出拍摄": (
            "Use Cancel or Save on the right\\nto exit capture"
        ),
    }
    for key, en in en_patches.items():
        if key in table and table[key].get("en") != en:
            table[key]["en"] = en
            updated += 1
    return updated


def needs_ja_fix(key: str, row: dict[str, str]) -> bool:
    ja = row.get("ja", "")
    zh = row.get("zh_CN", "")
    en = row.get("en", "")
    if key in JA:
        return ja != JA[key]
    if not ja or ja == zh:
        return True
    if ja == en and any("\u4e00" <= c <= "\u9fff" for c in key):
        return True
    return False


def main() -> int:
    text = GEN.read_text(encoding="utf-8")
    ns: dict = {}
    exec(compile(text.replace("__file__", repr(str(GEN))), str(GEN), "exec"), ns)
    table: dict = ns["TABLE"]
    updated = 0
    for key, row in table.items():
        if key in JA:
            if row.get("ja") != JA[key]:
                row["ja"] = JA[key]
                updated += 1
        elif needs_ja_fix(key, row):
            # keep existing if no dict entry
            pass
    # second pass: any still broken get ja from zh_TW or en as last resort with marker
    for key, row in table.items():
        if needs_ja_fix(key, row) and key not in JA:
            row["ja"] = row.get("zh_TW") or row.get("en") or key
            updated += 1

    updated += polish_ja_in_table(table)

    lines = ["TABLE: dict[str, dict[str, str]] = {"]
    for key in sorted(table.keys()):
        row = table[key]
        lines.append(f"    {key!r}: {{")
        lines.append(f'        "zh_CN": {row["zh_CN"]!r},')
        lines.append(f'        "zh_TW": {row["zh_TW"]!r},')
        lines.append(f'        "en": {row["en"]!r},')
        lines.append(f'        "ja": {row["ja"]!r},')
        lines.append("    },")
    lines.append("}")
    new_table = "\n".join(lines)
    start = text.index("TABLE: dict[str, dict[str, str]] = {")
    end = text.index("\n\nLOCALES", start)
    GEN.write_text(text[:start] + new_table + text[end:], encoding="utf-8")
    print(f"updated {updated} ja entries, TABLE size {len(table)}")
    return 0


